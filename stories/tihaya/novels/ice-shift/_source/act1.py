ACT = "Акт I · Первая тишина"


def _norm(step):
    """Python не даёт назвать аргумент `if`, поэтому принимаем if_ и пишем if."""
    if "if_" in step:
        step["if"] = step.pop("if_")
    return step


def n(sid, text, **kw):
    """Реплика рассказчика."""
    step = {"id": sid, "speaker": None, "text": text}
    step.update(kw)
    return _norm(step)


def s(sid, who, text, **kw):
    """Реплика персонажа."""
    step = {"id": sid, "speaker": who, "text": text}
    step.update(kw)
    return _norm(step)


def add(var, value=1):
    return {"var": var, "op": "add", "value": value}


def sub(var, value=1):
    return {"var": var, "op": "sub", "value": value}


def put(var, value):
    return {"var": var, "op": "set", "value": value}


def choice(text, goto, if_=None):
    item = {"text": text, "goto": goto}
    if if_:
        item["if"] = if_
    return item


